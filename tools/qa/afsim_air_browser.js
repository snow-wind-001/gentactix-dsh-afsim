async page => {
  const base='http://127.0.0.1:18900', checks=[], errors=[];
  const assert=(ok,text)=>{if(!ok)throw new Error(text);checks.push(text);};
  page.on('pageerror',e=>errors.push(String(e)));
  await page.addInitScript(()=>{window.gentactix={backendUrl:'http://127.0.0.1:18900'};localStorage.removeItem('gentactix-session');});
  const created=await page.request.post(base+'/api/sessions',{data:{scenario:'抗日战争-湘西会战-1945.04.09至1945.06.07',mission_id:'AJ18-local-v1',execution_backend:'afsim',persist_roles:false}});
  const {session_id:sid}=await created.json(), path=base+'/api/sessions/'+sid;
  const init=await page.request.post(path+'/init');assert(init.ok(),'real external initial load');
  let view=await (await page.request.get(path+'/commands')).json();
  const rev=v=>({expected_turn:v.turn,revision:v.revision,world_version:v.world_version});
  const saved=await page.request.put(path+'/commands',{data:{...rev(view),director:true,orders:view.units.map(u=>({unit_id:u.id,action:'hold',duration:'next'}))}});
  assert(saved.ok(),'complete manual hold batch excludes model generation');
  await page.setViewportSize({width:1366,height:900});await page.goto('http://127.0.0.1:18901/?air_audit='+Date.now());
  await page.getByRole('tab',{name:/已保存战局/}).click();
  await page.locator('button.open-battle').filter({hasText:sid}).click();
  await page.getByRole('button',{name:/^航空任务 ·/}).click();
  await page.getByTestId('air-operations').waitFor();
  assert((await page.getByTestId('air-operations').innerText()).includes('教学模型'),'air resource assumptions are visible');
  await page.getByRole('button',{name:'红方 红方教学编组1',exact:true}).click();
  await page.getByTestId('unit-action').selectOption('air_support');
  const target=page.getByLabel('敌方目标');await target.waitFor();
  await page.getByRole('button',{name:'地图选目标',exact:true}).click();
  await page.locator('.pick-banner').waitFor();
  await page.getByRole('button',{name:'蓝方 蓝方教学编组1',exact:true}).click();
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert((await target.inputValue())!=='','map-selected enemy is bound to the airstrike');
  const queued=page.waitForResponse(r=>r.url().endsWith('/commands')&&r.request().method()==='PUT');
  await page.getByTestId('enqueue-order').click();assert((await queued).ok(),'visual airstrike is accepted');
  view=await (await page.request.get(path+'/commands')).json();
  assert(view.orders.some(o=>o.action==='air_support'&&o.target_id),'air target survives queue normalization');
  const completed=page.waitForResponse(r=>r.url().endsWith('/next'),{timeout:90000});
  await page.getByTestId('command-toggle').click();
  await page.getByRole('button',{name:'⏩ 下一轮推演',exact:true}).click();
  const response=await completed,snapshot=await response.json();assert(response.ok(),'UI Next executes actual native airstrike');
  const panel=page.getByTestId('air-operations');await panel.waitFor();
  assert(await page.getByTestId('afsim-status').evaluate(e=>e.clientHeight>=100),'execution evidence remains readable above the map');
  assert(await page.locator('.leaflet-container').evaluate(e=>e.clientHeight>=300),'map keeps a usable height');
  assert((await panel.innerText()).includes('实际空袭减员 6 人'),'actual native air attribution is visible');
  assert((await page.locator('.strip').innerText()).includes('航空任务 1 项（打击 1'),'battle activity summary counts aviation separately from ground engagements');
  assert(await page.locator('.air-mission-route').count()===1,'native flight route is shown on the existing map');
  await page.getByRole('button',{name:'定位航空航路',exact:true}).click();
  await panel.scrollIntoViewIfNeeded();await page.screenshot({path:'.cache/qa/afsim-audit-20261027/air-browser-wide.png'});
  await page.setViewportSize({width:900,height:1000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'900px viewport has no horizontal overflow');
  await page.screenshot({path:'.cache/qa/afsim-audit-20261027/air-browser-narrow.png'});
  assert(!errors.length,'no uncaught browser exceptions');
  return {passed:true,session_id:sid,checks,air:snapshot.war_state.air_operations.assets.red};
}
