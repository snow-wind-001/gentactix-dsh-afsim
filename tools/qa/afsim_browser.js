async page => {
  const base = 'http://127.0.0.1:18900', checks = [], errors = [];
  const assert = (ok, text) => { if (!ok) throw new Error(text); checks.push(text); };
  page.on('pageerror', e => errors.push(String(e)));
  await page.addInitScript(() => { window.gentactix = { backendUrl: 'http://127.0.0.1:18900' }; localStorage.removeItem('gentactix-session'); });
  await page.setViewportSize({width:1366, height:900});
  await page.goto('http://127.0.0.1:18901');
  await page.locator('.battle-option').first().click();
  await page.getByRole('button', {name:/继续配置/}).click();
  const backend = page.getByTestId('execution-backend');
  assert(await backend.inputValue() === 'narrative', 'legacy execution remains default');
  await backend.selectOption('afsim');
  assert(await page.getByText('历史武器效能需要另行建模。', {exact:false}).isVisible(), 'scope is visible before creation');
  await page.screenshot({path:'.cache/qa/afsim-bridge/browser/selection-wide.png'});
  await page.route(base + '/api/health', async route => {
    const r = await route.fetch(), body = await r.json();
    body.afsim = {available:false, verified:false, missing:['fixture: missing mission.exe']};
    await route.fulfill({response:r,json:body});
  });
  await page.reload();
  await page.locator('.battle-option').first().click();
  await page.getByRole('button', {name:/继续配置/}).click();
  assert(await backend.locator('option[value=afsim]').isDisabled(), 'missing runtime disables new AFSIM selection');
  await page.unroute(base + '/api/health');
  await page.reload();
  await page.getByRole('tab', {name:/已保存战局/}).click();
  await page.locator('button').filter({hasText:'b5a9394e4ae4'}).first().click();
  const status = page.getByTestId('afsim-status');
  await status.waitFor();
  assert((await status.innerText()).includes('实际执行完成'), 'real native execution evidence is restored');
  assert((await status.innerText()).includes('固定教学规则'), 'motion and ledger effects have distinct sources');
  await status.locator('summary').click();
  assert((await status.innerText()).includes('dsh-native-mcp'), 'native MCP evidence can be inspected');
  await page.getByRole('button', {name:'红方 红方教学编组1',exact:true}).click();
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  await page.getByRole('button', {name:'本单位决策／执行回执',exact:true}).click();
  const receipt = page.locator('[aria-label=单位决策记录]');
  await receipt.waitFor();
  assert((await receipt.innerText()).includes('AFSIM实际位移'), 'unit receipt distinguishes actual execution from intent');
  const before = await (await page.request.get(base + '/api/sessions/b5a9394e4ae4')).json();
  const resultReady = page.waitForResponse(r => r.url().endsWith('/commands/compare'));
  await page.getByRole('button', {name:'只读对照：上轮本单位待命',exact:true}).click();
  const response = await resultReady, comparison = await response.json();
  assert(response.ok() && comparison.mode === 'controlled_afsim', 'unit counterfactual uses a real external-engine branch');
  const after = await (await page.request.get(base + '/api/sessions/b5a9394e4ae4')).json();
  assert(JSON.stringify(before.war_state) === JSON.stringify(after.war_state) && before.turn_count === after.turn_count, 'counterfactual leaves main world and clock unchanged');
  await page.screenshot({path:'.cache/qa/afsim-bridge/browser/workspace-wide.png'});
  await page.setViewportSize({width:900,height:1000});
  await status.scrollIntoViewIfNeeded();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), '900px viewport has no page overflow');
  await page.screenshot({path:'.cache/qa/afsim-bridge/browser/workspace-narrow.png'});
  assert(errors.length === 0, 'no uncaught browser exceptions');
  return {passed:true, checks, counterfactual:comparison.mode, external:comparison.external_execution.source};
}
