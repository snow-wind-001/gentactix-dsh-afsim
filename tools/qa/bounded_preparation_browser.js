async page=>{
 const checks=[];const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label)};
 const base='http://127.0.0.1:18988';
 const sessions=await (await page.request.get(base+'/api/sessions')).json();
 const sid=sessions.sessions[0].session_id;
 await page.addInitScript(({base,sid})=>{window.gentactix={backendUrl:base};localStorage.setItem('gentactix-session',sid)},{base,sid});
 await page.goto('http://127.0.0.1:18989/',{waitUntil:'domcontentloaded'});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('tab',{name:/已保存战局/}).click();
 await page.locator('.saved-battle').first().getByRole('button',{name:/打开|继续|恢复/}).first().click();
 await page.getByTestId('command-toggle').click();
 const panel=page.getByTestId('command-panel');
 const queued=panel.locator('.queued').first();await queued.waitFor();
 check((await queued.innerText()).includes('持续至T+2结束'),'confirmed deadline visible in queue');
 await queued.getByRole('button',{name:'编辑',exact:true}).click();
 await panel.getByTestId('preparation-deadline').waitFor();
 check((await panel.getByTestId('preparation-deadline').innerText()).includes('1944-03-05 02:50:00'),'end time derived from 01:50 plus two 30-minute turns');
 await panel.getByLabel('准备行动截止回合').fill('3');
 check((await panel.getByTestId('preparation-deadline').innerText()).includes('03:20:00'),'edited end time recalculated');
 const response=page.waitForResponse(r=>r.url()===base+'/api/sessions/'+sid+'/commands'&&r.request().method()==='PUT');
 await panel.getByTestId('enqueue-order').click();
 check((await response).ok(),'real API accepted edited deadline');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByRole('tab',{name:/已保存战局/}).click();
 await page.locator('.saved-battle').first().getByRole('button',{name:/打开|继续|恢复/}).first().click();
 await page.getByTestId('command-toggle').click();
 check((await panel.locator('.queued').first().innerText()).includes('持续至T+3结束'),'deadline persisted after reload');
 await panel.locator('.queued').first().getByRole('button',{name:'编辑',exact:true}).click();
 await page.screenshot({path:'.cache/qa/bounded-preparation-2026-10-29/browser/desktop.png'});
 await page.setViewportSize({width:900,height:900});
 await page.screenshot({path:'.cache/qa/bounded-preparation-2026-10-29/browser/narrow.png'});
 const box=await panel.boundingBox();check(!!box&&box.x>=0&&box.x+box.width<=900,'panel stays inside narrow viewport');
 const cancelled=page.waitForResponse(r=>r.url().startsWith(base+'/api/sessions/'+sid+'/commands/')&&r.request().method()==='DELETE');
 await panel.locator('.queued').first().getByRole('button',{name:'撤销',exact:true}).click();
 check((await cancelled).ok(),'cancel uses real API');
 await panel.getByText('暂无已确认命令。下令不会立即改变战局。',{exact:true}).waitFor();
 check((await (await page.request.get(base+'/api/sessions/'+sid)).json()).turn_count===0,'editing and cancellation never advanced the game');
 return {passed:true,checks,api_mocks:false,sid};
}
