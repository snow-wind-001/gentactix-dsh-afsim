async page=>{
 const API='http://127.0.0.1:19108',checks=[],errors=[];
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const get=async path=>{const r=await page.request.get(API+'/api'+path);if(!r.ok())throw Error(await r.text());return r.json();};
 const sessions=(await get('/sessions')).sessions;
 const match=sessions.find(s=>s.scenario==='多方向目标图前端验收（数值QA）');if(!match)throw Error('Run campaign_plan_ui_setup first');
 const sid=match.session_id,base='/sessions/'+sid;
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(id=>{window.gentactix={backendUrl:'http://127.0.0.1:19108'};localStorage.setItem('gentactix-session',id);},sid);
 await page.setViewportSize({width:1440,height:1000});await page.goto('http://127.0.0.1:19088');
 await page.getByRole('button',{name:'返回当前战局',exact:true}).click();
 const mission=page.getByTestId('mission-panel'),goals=page.getByTestId('campaign-objectives');
 const goalButton=page.getByRole('button',{name:/目标与运行/});
 const showGoals=async()=>{if(!await goals.isVisible())await goalButton.click();await goals.waitFor({state:'visible'});};
 await showGoals();let snap=await get(base);check(snap.turn_count===0,'Fresh UI game starts before any physical turn');
 check(await goals.locator('[data-goal-id]').count()===4,'Four typed direction/dependency goals displayed');
 check(await page.locator('.campaign-goal-region').count()===3,'Three actual goal regions replace the single legacy point circle');
 check((await goals.innerText()).includes('0 / 1'),'Required consecutive goal samples visible for both teams');
 const world=JSON.stringify(snap.war_state);await goals.getByLabel('目标阵营',{exact:true}).selectOption('blue');
 check(await goals.locator('[data-goal-id]').count()===1,'Team filter isolates blue objective');
 check(JSON.stringify((await get(base)).war_state)===world,'Filtering never changes world state');
 await goals.getByLabel('目标阵营',{exact:true}).selectOption('all');await goalButton.click();
 await page.getByTestId('command-toggle').click();const panel=page.getByTestId('command-panel');await panel.waitFor({state:'visible'});
 const unitMenu=panel.getByRole('combobox',{name:'单位名单（含无坐标单位）',exact:true});
 const enqueue=async()=>{const response=page.waitForResponse(r=>r.url()===API+'/api'+base+'/commands'&&r.request().method()==='PUT');
   await panel.getByTestId('enqueue-order').click();const r=await response;if(!r.ok())throw Error(await r.text());};
 const move=async(name,index)=>{
  await unitMenu.selectOption({label:'红 · '+name});await panel.getByTestId('unit-action').selectOption('move');
  await panel.getByRole('button',{name:'地图选目的地',exact:true}).click();
  const box=await page.locator('.campaign-goal-region').nth(index).boundingBox();if(!box)throw Error('Goal region has no map geometry');
  await page.mouse.click(box.x+box.width/2,box.y+box.height/2);await panel.waitFor({state:'visible'});
  check((await panel.getByTestId('map-destination').innerText()).includes('目的地 '),'Map supplies '+name+' target without coordinate entry');
  await enqueue();
 };
 const advance=async()=>{const response=page.waitForResponse(r=>r.url()===API+'/api'+base+'/next'&&r.request().method()==='POST',{timeout:180000});
  await page.getByRole('button',{name:'推进一轮',exact:true}).click();const r=await response;const d=await r.json();if(!r.ok())throw Error(JSON.stringify(d));return d;};
 await move('第159师',0);snap=await advance();
 check(snap.war_state.campaign_plan.nodes.north.status==='completed','Actual native map movement completes north goal');
 check(snap.war_state.mission.status==='active','Single direction success does not end the campaign');
 await showGoals();check((await goals.locator('[data-goal-id=preserve]').innerText()).includes('等待前置目标'),'Dependency remains visibly blocked');
 await page.screenshot({path:'.cache/qa/campaign-plan-2026-10-31/browser/partial-1440.png'});await goalButton.click();
 if(!await panel.isVisible())await page.getByTestId('command-toggle').click();
 await unitMenu.selectOption({label:'红 · 第159师'});await panel.getByTestId('unit-action').selectOption('hold');await enqueue();
 await move('第51师',1);snap=await advance();
 check(snap.war_state.mission.status==='completed'&&snap.war_state.mission.winner==='red','Second direction plus preservation triggers program settlement');
 await showGoals();check((await goals.locator('[data-goal-id=preserve]').innerText()).includes('已达成'),'Final dependent goal visibly completes');
 await mission.getByText('目标进度、补给账与重放凭据',{exact:true}).click();
 const compare=page.waitForResponse(r=>r.url()===API+'/api'+base+'/counterfactual'&&r.request().method()==='POST',{timeout:180000});
 await mission.getByRole('button',{name:/对照上一轮：红方全部原地待命/}).click();const r=await compare,d=await r.json();if(!r.ok())throw Error(JSON.stringify(d));
 const metric=d.metrics.find(m=>m.metric==='会战目标图已结算');check(metric?.factual===1&&metric.alternative===0,'UI-triggered actual native intervention changes whole-goal outcome');
 check(JSON.stringify((await get(base)).war_state)===JSON.stringify(snap.war_state),'Counterfactual leaves main world unchanged');
 await page.screenshot({path:'.cache/qa/campaign-plan-2026-10-31/browser/completed-1440.png'});
 await page.setViewportSize({width:900,height:1000});await page.screenshot({path:'.cache/qa/campaign-plan-2026-10-31/browser/completed-900.png'});
 await page.reload();await page.getByRole('button',{name:'返回当前战局',exact:true}).click();await showGoals();
 check((await get(base)).turn_count===2,'Reload retains exact completed turn without duplicate execution');
 check((await goals.locator('[data-goal-id=preserve]').innerText()).includes('已达成'),'Goal state survives UI reload');
 check(errors.length===0,'No browser page errors');
 return {passed:true,checks,session_id:sid,actual_api:true,actual_afsim:true,api_mocks:false,scope:'Six sourced identities with explicit numerical QA goal regions; no historical calibration or autonomous task execution claim'};
}
