 await page.getByLabel('编制范围',{exact:true}).selectOption('campaign');
 const picker=page.getByLabel('会战窗口',{exact:true});
 await picker.locator('option[value="WJL-oct6-10@1.0.0"]').waitFor({state:'attached'});
 await picker.selectOption('WJL-oct6-10@1.0.0');
 await page.getByTestId('campaign-window-scope').waitFor();
 const version=page.getByLabel('史料档案版本',{exact:true});
 const phase=page.getByLabel('历史起始阶段',{exact:true});
 check(await version.inputValue()==='1.3.0'&&await version.isDisabled(),'Fixed window pins source 1.3.0');
 check(await phase.inputValue()==='oct6_orders'&&await phase.isDisabled(),'Fixed window pins Oct 6 opening');
 check((await page.getByTestId('historical-basis').innerText()).includes('22个不重叠计算单位'),'22 candidates disclosed, not a two-unit reduction');
 check((await page.getByTestId('campaign-window-scope').innerText()).includes('不是22个完整建制同时在场'),'Candidate scope does not claim complete simultaneous formations');
 const exclusions=page.getByTestId('historical-exclusions');
 await exclusions.locator('summary').click();
 check((await exclusions.innerText()).includes('第61师'),'Later identity remains an excluded source reference');
 await exclusions.locator('summary').click();
 check((await page.getByTestId('historical-window').innerText()).includes('1938-10-11 00:00:00'),'Five-day reference boundary visible');
 check(await page.getByTestId('generate-historical-scenario').isEnabled(),'Native skill generation remains available');
 check(await page.locator('[data-historical-actor]').count()===0,'Unknown parameters do not become invented deployed units');
 const evidence=page.getByTestId('campaign-window-evidence');
