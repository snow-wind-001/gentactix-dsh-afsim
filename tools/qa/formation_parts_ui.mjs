import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from '../../frontend/node_modules/typescript/lib/typescript.js';
const source=fs.readFileSync('frontend/src/formation-parts.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {formationPartsPreview,formationPartIssues,formationGroupSummaries}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const draft=JSON.parse(fs.readFileSync('.cache/qa/formation-partitions/historical-draft.json','utf8'));
const params=draft.parameters,original=structuredClone(draft.preview_world),checks=[];
const check=(value,label)=>{assert.ok(value,label);checks.push(label)};
check(formationPartIssues(params.partitions,params.actors).length===0,'actual DSH-built partition input passes frontend checks');
const preview=formationPartsPreview(original,params.actors,params.partitions);
check(preview.red_units.length===3&&preview.blue_units.length===3,'preview has six leaves and no duplicate parent');
check(preview.red_units.reduce((n,u)=>n+u.personnel.current,0)===4600,'preview conserves parent personnel');
check(formationPartsPreview(preview,params.actors,params.partitions).red_units.length===3,'repeated preview does not split parts again');
const summary=formationGroupSummaries(preview)[0];
check(summary.current===1600&&summary.food===80&&summary.ammo===80,'parent stock equivalents are eighty rather than twice eighty');
const changed=structuredClone(params.partitions);changed.groups['lm.red.cmc_column'].parts[1].personnel++;
check(formationPartIssues(changed,params.actors).some(s=>s.includes('人员合计')),'personnel mismatch is visible before validation');
const collapsed=formationPartsPreview(preview,params.actors);
check(collapsed.red_units.length===2&&!collapsed.formation_groups,'removing draft partitions restores one parent preview');
check(collapsed.red_units[0].personnel.current===1600,'merged draft restores parent count');
assert.deepEqual(draft.preview_world,original);checks.push('preview does not mutate committed draft or source snapshot');
fs.writeFileSync('.cache/qa/formation-partitions/ui-helper-results.json',JSON.stringify({passed:true,checks},null,2)+'\n');
console.log(JSON.stringify({passed:true,checks}));
