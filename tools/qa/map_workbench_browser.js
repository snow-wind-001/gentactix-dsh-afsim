async page => {
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:18901/');
  await page.getByRole('tab',{name:/已保存战局/}).click();
  await page.locator('[data-session-id="84b4267a9109"] .open-battle').click();
  await page.getByTestId('map-workbench').waitFor();
  const before=await (await page.request.get('http://127.0.0.1:8700/api/sessions/84b4267a9109')).json();
  const map=page.getByRole('region',{name:'战场态势地图',exact:true});
  const original=await map.boundingBox();
  assert(original.width>1300&&original.height>800,'map does not occupy the workspace');
  for(const name of ['left-panel','top-panel','analysis-panel'])assert(!(await page.getByTestId(name).isVisible()),name+' should start collapsed');
  await page.getByTestId('top-controls').click();
  const intent=page.getByLabel('本轮决策意图');
  await intent.fill('布局验证草稿：仅检查展示，不提交命令。');
  await page.getByTestId('top-controls').click();
  assert(!(await intent.isVisible()),'top did not fold');
  await page.getByTestId('top-controls').click();
  assert(await intent.inputValue()==='布局验证草稿：仅检查展示，不提交命令。','intent lost on folding');
  await intent.press('Escape');
  assert(await page.getByTestId('top-controls').evaluate(el=>el===document.activeElement),'Escape did not restore focus');
  await page.getByTestId('left-toggle').click();
  await page.getByTestId('left-panel').waitFor({state:'visible'});
  await page.getByTestId('left-panel').getByRole('button',{name:'收起想定与控制'}).click();
  await page.getByRole('tab',{name:'兵种与保障',exact:true}).click();
  assert(await page.getByTestId('combined-unit').count()===6,'classified ledger missing');
  await page.getByRole('tab',{name:'兵种与保障',exact:true}).click();
  assert(!(await page.getByTestId('analysis-panel').isVisible()),'analysis did not fold');
  await page.getByTestId('top-layers').click();
  const labels=page.getByLabel('单位标注',{exact:true});
  const old=await labels.isChecked();await labels.setChecked(!old);
  await page.getByTestId('top-layers').click();await page.getByTestId('top-layers').click();
  assert(await labels.isChecked()===!old,'layer state lost');await labels.setChecked(old);
  await page.getByTestId('focus-map').click();
  const after=await map.boundingBox();
  assert(Math.abs(original.width-after.width)<2&&Math.abs(original.height-after.height)<2,'folding remounted or resized map');
  await page.screenshot({path:'.cache/qa/map-workbench/map-wide.png'});
  const state=await(await page.request.get('http://127.0.0.1:8700/api/sessions/84b4267a9109')).json();
  assert(JSON.stringify(before.war_state)===JSON.stringify(state.war_state),'layout changed battle');
  return {passed:true,map:after,panels:'top/left/right',draft_retained:true,layers_retained:true,world_unchanged:true};
}
