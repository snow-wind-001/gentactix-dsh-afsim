async page => {
  const API='http://127.0.0.1:18902';const checks=[];
  const assert=(ok,text)=>{if(!ok)throw new Error(text);checks.push(text);};
  const req=async(method,path,data)=>{const r=await page.request[method](API+path,data?{data}:{});if(!r.ok())throw new Error(await r.text());return r.json();};
  const rev=v=>({expected_turn:v.turn,revision:v.revision,world_version:v.world_version});
  assert((await req('get','/openapi.json')).info.version==='3.4.0','frozen backend 3.4.0');
  assert(await page.evaluate(()=>location.protocol==='file:'&&typeof require==='undefined'&&typeof process==='undefined'),'isolated packaged file renderer');
  const created=await req('post','/api/sessions',{scenario:'3.4.0实包地图指挥与存档验收',mission_id:'CA-AJ18-v1',execution_backend:'afsim',persist_roles:false});
  const sid=created.session_id,path='/api/sessions/'+sid;
  await req('post',path+'/init');
  let view=await req('get',path+'/commands');
  await req('put',path+'/commands',{...rev(view),director:true,orders:view.units.map(u=>({unit_id:u.id,action:'hold',duration:'next'}))});
  await page.evaluate(id=>localStorage.setItem('gentactix-session',id),sid);await page.reload();
  await page.getByRole('button',{name:'返回当前战局',exact:true}).click();
  await page.getByTestId('map-workbench').waitFor();
  assert((await page.title()).includes('3.4.0'),'renderer displays new version');
  for(const name of ['left-panel','analysis-panel','top-panel'])assert(!(await page.getByTestId(name).isVisible()),name+' default collapsed');
  await page.getByRole('tab',{name:'兵种与保障',exact:true}).click();
  assert(await page.getByTestId('combined-unit').count()===6,'all classified unit ledgers accessible');
  const marker=page.getByRole('button',{name:'红方 红方教学步兵团',exact:true});
  await marker.click();await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert(!(await page.getByTestId('analysis-panel').isVisible()),'unit selection closes analysis overlay');
  await page.getByTestId('unit-action').selectOption('move');
  await page.getByRole('combobox',{name:'持续方式'}).selectOption('until_arrived');
  await page.getByRole('button',{name:'地图选目的地',exact:true}).click();
  const box=await marker.boundingBox();
  await page.mouse.click(box.x+box.width/2+18,box.y+box.height/2+18);
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert((await page.getByTestId('map-destination').innerText()).includes('目的地 '),'map point returns to command draft');
  const queued=page.waitForResponse(r=>r.url()===API+path+'/commands'&&r.request().method()==='PUT');
  await page.getByTestId('enqueue-order').click();assert((await queued).ok(),'visual move order confirms');
  const done=page.waitForResponse(r=>r.url()===API+path+'/next',{timeout:120000});
  await page.getByRole('button',{name:'推进一轮',exact:true}).click();
  const response=await done,result=await response.json();if(!response.ok())throw new Error(JSON.stringify(result));checks.push('manual turn committed');
  assert(result.afsim.model_skipped&&result.afsim.source==='dsh_native_mcp_controller','manual batch runs native AFSIM');
  const moved=result.war_state.red_units[0];
  assert(moved.formation.last_execution.distance_milli>0,'actual native movement recorded');
  assert((await req('get',path+'/unit-decisions')).total===result.turn_count*6,'six execution records per turn');
  await page.getByTestId('top-status').click();await page.getByTestId('mission-panel').waitFor({state:'visible'});
  await page.screenshot({path:'.cache/qa/map-workbench/packaged-status.png'});
  await page.getByTestId('top-controls').click();
  await page.getByRole('button',{name:'模型配置',exact:true}).click();
  await page.locator('#llm-model').waitFor({state:'visible'});checks.push('model configuration dialog available');
  await page.getByRole('button',{name:'完成',exact:true}).click();
  // Verify generated bytes without opening a native save portal in Xvfb.
  await page.evaluate(()=>{const original=URL.createObjectURL;window.qaExportBlob=null;window.qaOriginalBlobURL=original;URL.createObjectURL=blob=>{window.qaExportBlob=blob;return original(blob);};window.qaAnchorClick=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){if(this.download){window.qaExportName=this.download;return;}window.qaAnchorClick.call(this);};});
  await page.getByRole('button',{name:'导出战局',exact:true}).click();
  await page.waitForFunction(()=>!!window.qaExportBlob);
  const exported=await page.evaluate(async()=>{const text=await window.qaExportBlob.text();URL.createObjectURL=window.qaOriginalBlobURL;HTMLAnchorElement.prototype.click=window.qaAnchorClick;return text;});
  assert(/"terrain_factor"\s*:\s*1\.0\b/.test(exported),'export preserves numeric lexemes');
  await page.getByRole('button',{name:'导入战局',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'导入已保存战局',exact:true});
  await dialog.getByLabel('战局 JSON 文件',{exact:true}).evaluate((input,json)=>{
    const transfer=new DataTransfer();transfer.items.add(new File([json],'campaign.json',{type:'application/json'}));input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));
  },exported);
  await dialog.getByTestId('import-preview').waitFor();
  assert(await dialog.getByRole('button',{name:'确认导入并打开',exact:true}).isDisabled(),'import preserves existing battle');
  await req('delete',path);
  await dialog.getByLabel('战局 JSON 文件',{exact:true}).evaluate((input,json)=>{
    const transfer=new DataTransfer();transfer.items.add(new File([json],'campaign.json',{type:'application/json'}));input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));
  },exported);
  await dialog.getByRole('button',{name:'确认导入并打开',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('.import-dialog button.primary')?.disabled);
  await dialog.getByRole('button',{name:'确认导入并打开',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert(JSON.stringify((await req('get',path)).war_state)===JSON.stringify(result.war_state),'UI export/import roundtrip preserves combined world');
  await page.getByTestId('focus-map').click();
  await page.screenshot({path:'.cache/qa/map-workbench/packaged-map.png'});
  return {passed:true,checks,session_id:sid,turn:result.turn_count};
}
