import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../frontend/package.json',import.meta.url));
const {build}=require('esbuild');
const bundle=await build({stdin:{contents:"export {mdToHtml} from './frontend/src/markdown.ts';",resolveDir:process.cwd(),loader:'ts'},bundle:true,format:'esm',platform:'node',write:false});
const {mdToHtml}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].contents).toString('base64'));
const table='说明\n\n| 单位 | 人数 |\n| --- | ---: |\n| **第31师** | 5264 |\n| 蓝方装甲队 | 590 |\n\n结尾';
const out=mdToHtml(table);
assert.match(out,/<table>/);assert.match(out,/<th scope="col">单位<\/th>/);
assert.equal((out.match(/<tr>/g)||[]).length,3);assert.match(out,/<td><b>第31师<\/b><\/td>/);
assert.match(out,/tabindex="0"/);assert.match(out,/说明/);assert.match(out,/结尾/);
assert.match(mdToHtml('| 字段 | 值 |\n| --- | --- |\n| `fire\\|move` | 2 |'),/<td><code>fire\|move<\/code><\/td>/);
const malicious=mdToHtml('| 单位 | 数量 |\n| --- | --- |\n| <img src=x onerror=alert(1)> | **<script>bad()</script>** |');
assert.doesNotMatch(malicious,/<img|<script/i);assert.match(malicious,/&lt;img/);
assert.match(mdToHtml('普通 | 文字\n不是表格'),/普通 \| 文字<br\/>不是表格/);
assert.match(mdToHtml('## 标题\n- **重点**\n`safe`'),/<h4>标题<\/h4><br\/>• <b>重点<\/b><br\/><code>safe<\/code>/);
assert.match(mdToHtml('| a | b |\n| --- | --- |\n| 1 | 2 | 3 |'),/1 \| 2 \| 3/);
assert.doesNotMatch(mdToHtml('```\n| a | b |\n| --- | --- |\n| 1 | 2 |\n```'),/<table>/);
console.log('PASS Markdown table semantics, escaped pipes, safe HTML, legacy formatting and fenced examples');
