async page => {
  const API='http://127.0.0.1:18902',checks=[];
  const assert=(ok,text)=>{if(!ok)throw new Error(text);checks.push(text);};
  const call=async(method,path,data)=>{const r=await page.request[method](API+path,data?{data}:{});if(!r.ok())throw new Error(await r.text());return r.json();};
  const created=await call('post','/api/sessions',{scenario:'等待反馈与交互验收',mission_id:'CA-AJ18-v1',execution_backend:'afsim',persist_roles:false});
  const sid=created.session_id,path='/api/sessions/'+sid;
  await call('post',path+'/init');
  let view=await call('get',path+'/commands');
  await call('put',path+'/commands',{expected_turn:view.turn,revision:view.revision,world_version:view.world_version,director:true,orders:view.units.map(u=>({unit_id:u.id,action:'hold',duration:'next'}))});
  await page.context().addInitScript(id=>{window.gentactix={backendUrl:'http://127.0.0.1:18902'};localStorage.setItem('gentactix-session',id);},sid);
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:18901/');
  await page.getByRole('button',{name:'返回当前战局',exact:true}).click();
  let runtime={active:true,progress:{steps:0,tokens:0}},mode='real',release;
  let polls=0,nexts=0,cancels=0,failPoll=false;
  await page.route(API+path+'/progress',route=>{polls++;return route.fulfill(failPoll?{status:503,json:{detail:'测试状态连接中断'}}:{json:runtime});});
  await page.route(API+path+'/cancel',route=>{cancels++;return route.fulfill({json:{ok:true,note:'测试：取消请求已确认'}});});
  const nextRoute=async route=>{nexts++;await new Promise(resolve=>release=resolve);if(mode==='real')await route.continue();else await route.fulfill({status:mode==='cancel'?409:503,json:{detail:mode==='cancel'?'已取消：测试候选未提交':'测试执行失败：原战局保持不变'}});};
  await page.route(API+path+'/next',nextRoute);
  const marker=page.getByRole('button',{name:'红方 红方教学步兵团',exact:true});
  await marker.evaluate(el=>window.qaMarker=el);
  await marker.click();
  assert(await marker.evaluate(el=>el===window.qaMarker),'selection preserves marker DOM');
  assert(await page.locator('.leaflet-popup').count()===0,'unique unit selection has no duplicate popup');
  await page.getByTestId('focus-map').click();
  assert(!(await page.getByTestId('command-panel').isVisible()),'focus map hides command panel');
  const advance=page.getByRole('button',{name:'推进一轮',exact:true});
  const clickBox=await advance.boundingBox();
  await advance.click();
  const bar=page.getByTestId('operation-progress');
  await bar.waitFor({state:'visible'});
  assert(await bar.getAttribute('data-state')==='running','pending is visible before response');
  assert(await bar.getAttribute('aria-valuenow')===null,'unknown duration has no fake percent');
  assert(await advance.isDisabled(),'advance disabled while working');
  await page.mouse.click(clickBox.x+clickBox.width/2,clickBox.y+clickBox.height/2);
  assert(nexts===1&&cancels===0,'second click neither re-submits nor cancels');
  await page.waitForFunction(()=>{const clock=document.querySelector('[data-testid=operation-elapsed]');return clock&&clock.textContent!=='00:00';});
  failPoll=true;
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-status]')?.textContent.includes('状态连接暂不可用'));
  assert(await bar.getAttribute('data-state')==='running','status connection loss does not pretend to finish');
  failPoll=false;
  runtime={active:true,progress:{steps:4,tokens:2000}};
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-status]')?.textContent.includes('DSH决策中'));
  const start=Date.now();await page.getByRole('tab',{name:'兵种与保障',exact:true}).click();
  await page.getByTestId('analysis-panel').waitFor({state:'visible'});
  const panelLatency=Date.now()-start;
  assert(panelLatency<700,'analysis remains interactive while waiting');
  assert(await marker.evaluate(el=>el===window.qaMarker),'polls do not replace markers');
  await page.getByTestId('top-layers').click();
  const ranges=page.getByLabel('火力射程',{exact:false});await ranges.uncheck();
  assert(await page.locator('.bf-aggregate-range').count()===0,'range switch hides aggregate ranges');
  await ranges.check();assert(await page.locator('.bf-aggregate-range').count()>0,'range switch restores aggregate ranges');
  assert(await marker.evaluate(el=>el===window.qaMarker),'range toggles preserve unit markers');
  runtime={active:true,progress:{phase:'afsim_execution',steps:4,tokens:2000}};
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-stage')==='external');
  await page.getByTestId('focus-map').click();
  await page.screenshot({path:'.cache/qa/turn-feedback/waiting-wide.png'});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'pending header fits phone');
  await page.screenshot({path:'.cache/qa/turn-feedback/waiting-phone.png'});
  await page.setViewportSize({width:1440,height:1000});
  const done=page.waitForResponse(r=>r.url()===API+path+'/next',{timeout:120000});
  release();const response=await done;const result=await response.json();
  assert(response.ok()&&result.turn_count===1&&result.afsim.model_skipped,'real native manual turn committed');
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-state')==='success');
  let count=polls;await page.waitForTimeout(1400);assert(polls===count,'polling stops after commit');
  await page.screenshot({path:'.cache/qa/turn-feedback/completed.png'});
  mode='cancel';runtime={active:true,progress:{steps:1,tokens:100}};
  await advance.click();await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-state')==='running');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-status]')?.textContent.includes('等待确认'));
  assert(await bar.getAttribute('data-state')==='running','cancel request does not pretend to finish');
  let finished=page.waitForResponse(r=>r.url()===API+path+'/next');release();await finished;
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-state')==='cancelled');
  mode='error';await advance.click();await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-state')==='running');
  finished=page.waitForResponse(r=>r.url()===API+path+'/next');release();await finished;
  await page.waitForFunction(()=>document.querySelector('[data-testid=operation-progress]')?.getAttribute('data-state')==='failed');
  assert((await call('get',path)).turn_count===1,'cancel/failure display fixtures preserve world');
  await page.screenshot({path:'.cache/qa/turn-feedback/failed.png'});
  return {passed:true,session_id:sid,checks,panelLatencyMs:panelLatency,phase_fixture:true,native_final_result:true};
}
